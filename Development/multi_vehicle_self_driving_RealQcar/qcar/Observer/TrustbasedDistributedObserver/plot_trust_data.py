def _load_csv(filepath: str) -> Tuple[List[str], List[Dict[str, str]]]:
    """Return (columns, rows-as-dicts) from a CSV file, filtering corrupt lines."""
    cleaned_lines = []
    with open(filepath, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            # Remove null bytes which can result from abrupt process termination
            line = line.replace('\x00', '')
            # Skip any lines that are still absurdly long (corrupted)
            if len(line) < 131072:
                cleaned_lines.append(line)
                
    reader = csv.DictReader(cleaned_lines)
    columns = reader.fieldnames or []
    rows = list(reader)
    return columns, rows


def _col_to_array(rows: List[dict], col: str) -> np.ndarray:
    """Convert a column to a float numpy array (NaN for missing/bad)."""
    vals = []
    for row in rows:
        raw = row.get(col, "")
        try:
            vals.append(float(raw))
        except (ValueError, TypeError):
            vals.append(float("nan"))
    return np.array(vals, dtype=float)


def _col_to_text(rows: List[dict], col: str) -> List[str]:
    """Convert a column to a list of stripped strings."""
    vals: List[str] = []
    for row in rows:
        raw = row.get(col, "")
        vals.append("" if raw is None else str(raw).strip())
    return vals


def _extract_vehicle_ids(columns: List[str]) -> List[int]:
    ids = set()
    prefixes = {
        "vehicle_present", "trust", "gtrust", "w_neighbor",
        "w0_final", "w_self_final", "w_neighbor_sum_final",
        "est_conf", "pred_mode", "est_x", "est_v",
        "v_score", "d_score", "a_score", "h_score",
        "b_score", "q_factor", "local_trust", "global_trust",
        "gamma_host", "gamma_local_peer", "gamma_self",
        "d_host_mean", "d_local_mean", "d_self",
        "mi_dist", "mi_veh_id", "mi_elem_idx", "mi_elem_val",
    }
    for col in columns:
        m = re.search(r"_(\d+)$", col)
        if m and col[: m.start()] in prefixes:
            ids.add(int(m.group(1)))
    return sorted(ids)


def _active_vehicles(rows: List[dict], columns: List[str],
                     vehicle_ids: List[int]) -> List[int]:
    active = []
    for vid in vehicle_ids:
        for prefix in ("vehicle_present", "trust", "gtrust",
                       "w_neighbor", "w0_final", "w_self_final",
                       "w_neighbor_sum_final", "est_conf", "est_x"):
            col = f"{prefix}_{vid}"
            if col not in columns:
                continue
            arr = _col_to_array(rows, col)
            if prefix == "vehicle_present" and np.nanmax(arr) > 0:
                active.append(vid)
                break
            elif prefix != "vehicle_present" and np.any(np.isfinite(arr)):
                active.append(vid)
                break
    return active


def _has_finite_column(rows: List[dict], col: str) -> bool:
    return np.any(np.isfinite(_col_to_array(rows, col)))


def _plot_series(ax, times, rows, prefix, vids, label_fmt="Vehicle {}",
                 **kwargs):
    """Plot one series per vehicle. Returns count of plotted curves."""
    n = 0
    for vid in vids:
        col = f"{prefix}_{vid}"
        arr = _col_to_array(rows, col)
        if np.any(np.isfinite(arr)):
            ax.plot(times, arr, label=label_fmt.format(vid), **kwargs)
            n += 1
    return n


def _no_data(ax, title: str):
    ax.set_title(title, fontsize=10, fontweight="bold")
    ax.text(0.5, 0.5, "No data", ha="center", va="center",
            transform=ax.transAxes, fontsize=11, color="#888")


def _style(ax, title="", ylabel="", xlabel="", legend=True):
    if title:
        ax.set_title(title, fontsize=10, fontweight="bold")
    if ylabel:
        ax.set_ylabel(ylabel, fontsize=9)
    if xlabel:
        ax.set_xlabel(xlabel, fontsize=9)
    ax.grid(True, linestyle="--", alpha=0.4)
    ax.tick_params(labelsize=8)
    if legend:
        handles, labels = ax.get_legend_handles_labels()
        if handles:
            # Avoid duplicate legend entries for Turn Section if plotted multiple times
            by_label = dict(zip(labels, handles))
            ax.legend(by_label.values(), by_label.keys(), fontsize=7, ncol=max(1, len(by_label) // 2),
                      loc="best", framealpha=0.7)


def _first_finite_index(*arrays: np.ndarray) -> int:
    """Return the first index where every array has a finite value."""
    if not arrays:
        return -1
    lengths = [len(np.asarray(arr)) for arr in arrays]
    if not lengths:
        return -1
    n = min(lengths)
    if n <= 0:
        return -1
    mask = np.ones(n, dtype=bool)
    for arr in arrays:
        arr_np = np.asarray(arr, dtype=float)[:n]
        mask &= np.isfinite(arr_np)
    idx = np.flatnonzero(mask)
    return int(idx[0]) if idx.size > 0 else -1

def _add_turn_sections(ax, times, rows):
    is_turning = _col_to_array(rows, "is_turning")
    if np.any(np.isfinite(is_turning)) and np.any(is_turning > 0):
        import matplotlib.transforms as mtransforms
        trans = mtransforms.blended_transform_factory(ax.transData, ax.transAxes)
        ax.fill_between(times, 0, 1, where=(is_turning >= 1), color='gold', alpha=0.25, transform=trans, label='Turn Section')


def _safe_float(value, default=float("nan")) -> float:
    try:
        return float(value)
    except (TypeError, ValueError):
        return default


def _rmse(values: np.ndarray) -> float:
    arr = np.asarray(values, dtype=float)
    arr = arr[np.isfinite(arr)]
    if arr.size == 0:
        return float("nan")
    return float(np.sqrt(np.mean(arr ** 2)))


def _last_nonempty_value(rows: List[dict], col: str) -> str:
    for row in reversed(rows):
        value = row.get(col, "")
        if value not in ("", None):
            return value
    return ""


def _json_list_or_empty(raw) -> List[dict]:
    if raw in ("", None):
        return []
    try:
        data = json.loads(raw)
    except (TypeError, ValueError, json.JSONDecodeError):
        return []
    if not isinstance(data, list):
        return []
    return [item for item in data if isinstance(item, dict)]


def _finite_time_bounds(times: np.ndarray) -> Tuple[float, float]:
    finite_times = np.asarray(times, dtype=float)
    finite_times = finite_times[np.isfinite(finite_times)]
    if finite_times.size == 0:
        return 0.0, 1.0
    t0 = float(np.min(finite_times))
    t1 = float(np.max(finite_times))
    if not math.isfinite(t1) or t1 <= t0:
        t1 = t0 + 1.0
    return t0, t1


def _clamped_interval(start, end, t_min: float, t_max: float) -> Tuple[float, float]:
    start_f = _safe_float(start)
    end_f = _safe_float(end)
    if not math.isfinite(start_f):
        start_f = t_min
    if not math.isfinite(end_f):
        end_f = t_max
    start_f = min(max(start_f, t_min), t_max)
    end_f = min(max(end_f, start_f), t_max)
    if end_f <= start_f:
        end_f = min(max(start_f + 1e-3, t_min), max(t_max, start_f + 1e-3))
    return start_f, end_f


def _attack_target_label(interval: dict) -> str:
    data_type = str(interval.get("data_type", "") or "attack").lower()
    attacker = interval.get("attacker_id", "")
    victims = interval.get("victim_ids", [])
    if not isinstance(victims, list):
        victims = [victims]
    if data_type == "local":
        return f"local V{attacker}"
    if data_type == "fleet":
        victim_text = "all" if -1 in victims else ",".join(f"V{v}" for v in victims)
        return f"fleet {victim_text}"
    if data_type == "both":
        victim_text = "all" if -1 in victims else ",".join(f"V{v}" for v in victims)
        return f"both V{attacker}->{victim_text}"
    return data_type


def _attack_display_label(interval: dict) -> str:
    parts = [
        str(interval.get("type", "") or "attack"),
        str(interval.get("modification", "") or ""),
        str(interval.get("data_type", "") or ""),
    ]
    fields = interval.get("target_fields", [])
    if isinstance(fields, list):
        fields = [str(f) for f in fields if str(f)]
        if fields:
            parts.append("/".join(fields))
    return " ".join(part for part in parts if part).strip()


def _attack_value_column(field: str, kind: str, vehicle_id: int) -> str:
    return f"inject_attack_{kind}_{field}_{vehicle_id}"


def _attack_field_has_data(rows: List[dict], columns: List[str],
                           active: List[int], field: str) -> bool:
    for vid in active:
        for kind in ("original", "modified", "delta"):
            col = _attack_value_column(field, kind, vid)
            if col in columns and _has_finite_column(rows, col):
                return True
    return False


def _plot_attack_value_panel(ax, times, rows, columns, active,
                             field: str, title: str, ylabel: str):
    plotted = 0
    cmap = plt.get_cmap("tab10")
    for idx, vid in enumerate(active):
        modified_col = _attack_value_column(field, "modified", vid)
        original_col = _attack_value_column(field, "original", vid)
        delta_col = _attack_value_column(field, "delta", vid)
        if modified_col not in columns and original_col not in columns:
            continue

        modified = _col_to_array(rows, modified_col)
        original = _col_to_array(rows, original_col)
        delta = _col_to_array(rows, delta_col)
        if not (
            np.any(np.isfinite(modified))
            or np.any(np.isfinite(original))
            or np.any(np.isfinite(delta))
        ):
            continue

        color = cmap(idx % 10)
        if np.any(np.isfinite(original)):
            ax.plot(
                times,
                original,
                linestyle="--",
                linewidth=1.1,
                alpha=0.65,
                color=color,
                label=f"V{vid} original",
            )
        if np.any(np.isfinite(modified)):
            ax.plot(
                times,
                modified,
                linewidth=1.8,
                color=color,
                label=f"V{vid} injected",
            )
        elif np.any(np.isfinite(delta)):
            ax.plot(
                times,
                delta,
                linewidth=1.6,
                color=color,
                label=f"V{vid} delta",
            )
        plotted += 1

    if plotted == 0:
        _no_data(ax, title)
    _style(ax, title, ylabel, xlabel="Time [s]")


def _extract_attack_intervals(rows: List[dict], columns: List[str],
                              active: List[int], times: np.ndarray) -> List[dict]:
    t_min, t_max = _finite_time_bounds(times)
    intervals: List[dict] = []

    raw_json = _last_nonempty_value(rows, "v2v_attack_intervals")
    for item in _json_list_or_empty(raw_json):
        start_s, end_s = _clamped_interval(
            item.get("start_s"), item.get("end_s"), t_min, t_max
        )
        interval = dict(item)
        interval["start_s"] = start_s
        interval["end_s"] = end_s
        interval["target_label"] = _attack_target_label(interval)
        interval["display_label"] = _attack_display_label(interval)
        intervals.append(interval)

    if intervals:
        return intervals

    seen = set()
    for vid in active:
        if f"inject_attack_start_{vid}" not in columns:
            continue
        for row in rows:
            start_f = _safe_float(row.get(f"inject_attack_start_{vid}", ""))
            if not math.isfinite(start_f):
                continue
            end_f = _safe_float(row.get(f"inject_attack_end_{vid}", ""))
            start_s, end_s = _clamped_interval(start_f, end_f, t_min, t_max)
            fields = str(row.get(f"inject_attack_fields_{vid}", "")).split("|")
            interval = {
                "name": row.get(f"inject_attack_name_{vid}", ""),
                "type": row.get(f"inject_attack_type_{vid}", ""),
                "modification": row.get(f"inject_attack_modification_{vid}", ""),
                "data_type": row.get(f"inject_attack_data_type_{vid}", ""),
                "target_fields": [f for f in fields if f],
                "start_s": start_s,
                "end_s": end_s,
                "attacker_id": row.get(f"inject_attack_attacker_{vid}", ""),
                "victim_ids": [vid],
                "target_label": f"V{vid}",
            }
            interval["display_label"] = _attack_display_label(interval)
            key = (
                interval["target_label"],
                interval["type"],
                interval["modification"],
                interval["data_type"],
                round(start_s, 6),
                round(end_s, 6),
            )
            if key in seen:
                continue
            seen.add(key)
            intervals.append(interval)

    if intervals:
        return intervals

    if "v2v_attack_start_s" in columns:
        for row in rows:
            start_f = _safe_float(row.get("v2v_attack_start_s", ""))
            if not math.isfinite(start_f):
                continue
            end_f = _safe_float(row.get("v2v_attack_end_s", ""))
            start_s, end_s = _clamped_interval(start_f, end_f, t_min, t_max)
            interval = {
                "type": row.get("v2v_attack_types", ""),
                "modification": "",
                "data_type": row.get("v2v_attack_data_types", ""),
                "target_fields": [],
                "start_s": start_s,
                "end_s": end_s,
                "attacker_id": "",
                "victim_ids": [],
                "target_label": "attack",
            }
            interval["display_label"] = _attack_display_label(interval)
            key = (
                interval["type"],
                interval["data_type"],
                round(start_s, 6),
                round(end_s, 6),
            )
            if key in seen:
                continue
            seen.add(key)
            intervals.append(interval)

    return intervals


def _mask_to_time_spans(times: np.ndarray, mask: np.ndarray) -> List[Tuple[float, float]]:
    times = np.asarray(times, dtype=float)
    mask = np.asarray(mask, dtype=bool)
    valid = np.isfinite(times)
    if times.size == 0 or mask.size != times.size or not np.any(valid & mask):
        return []

    valid_times = times[valid]
    positive_diffs = np.diff(valid_times)
    positive_diffs = positive_diffs[positive_diffs > 0.0]
    fallback_dt = float(np.median(positive_diffs)) if positive_diffs.size else 1e-3
    spans: List[Tuple[float, float]] = []
    start_idx = None
    for idx, is_on in enumerate(mask):
        if is_on and start_idx is None:
            start_idx = idx
        if start_idx is not None and (not is_on or idx == len(mask) - 1):
            end_idx = idx if is_on and idx == len(mask) - 1 else idx - 1
            start_t = times[start_idx]
            end_t = times[end_idx]
            if not (math.isfinite(start_t) and math.isfinite(end_t)):
                start_idx = None
                continue
            if end_t <= start_t:
                end_t = start_t + fallback_dt
            spans.append((float(start_t), float(end_t)))
            start_idx = None
    return spans


def _extract_attack_events(rows: List[dict], columns: List[str],
                           times: np.ndarray) -> List[dict]:
    raw_json = _last_nonempty_value(rows, "v2v_attack_events")
    events = _json_list_or_empty(raw_json)
    if events:
        return [
            {"event": str(e.get("event", "")), "time_s": _safe_float(e.get("time_s"))}
            for e in events
            if math.isfinite(_safe_float(e.get("time_s")))
        ]

    if "v2v_attack_enabled" not in columns:
        return []
    enabled = _col_to_array(rows, "v2v_attack_enabled")
    enabled_mask = np.isfinite(enabled) & (enabled >= 0.5)
    events = []
    prev = False
    for t, is_enabled in zip(times, enabled_mask):
        if not math.isfinite(float(t)):
            continue
        if is_enabled and not prev:
            events.append({"event": "enable", "time_s": float(t)})
        elif prev and not is_enabled:
            events.append({"event": "disable", "time_s": float(t)})
        prev = bool(is_enabled)
    return events


def _parse_vehicle_id_list(raw) -> List[int]:
    if raw in ("", None):
        return []
    if isinstance(raw, (list, tuple, set)):
        values = list(raw)
    else:
        values = str(raw).replace(",", "|").split("|")

    parsed: List[int] = []
    for value in values:
        text = str(value).strip()
        if not text:
            continue
        try:
            parsed.append(int(text))
        except (TypeError, ValueError):
            continue
    return sorted(set(parsed))


def _extract_rollback_events(rows: List[dict], columns: List[str],
                             times: np.ndarray) -> List[dict]:
    if "rollback_triggered" not in columns:
        return []

    events: List[dict] = []
    seen = set()
    for idx, row in enumerate(rows):
        triggered = _safe_float(row.get("rollback_triggered", 0.0), 0.0)
        if not math.isfinite(triggered) or triggered < 0.5:
            continue

        event_time = _safe_float(row.get("rollback_event_time_s", ""))
        if not math.isfinite(event_time):
            event_time = _safe_float(times[idx] if idx < len(times) else float("nan"))
        if not math.isfinite(event_time):
            continue

        total_rollbacks = int(_safe_float(row.get("rollback_total", 0.0), 0.0))
        active_vehicles = _parse_vehicle_id_list(row.get("rollback_active_vehicles", ""))
        newly_flagged = _parse_vehicle_id_list(row.get("rollback_newly_flagged", ""))
        key = (
            round(float(event_time), 6),
            total_rollbacks,
            tuple(active_vehicles),
            tuple(newly_flagged),
        )
        if key in seen:
            continue
        seen.add(key)
        events.append(
            {
                "time_s": float(event_time),
                "total_rollbacks": total_rollbacks,
                "active_count": len(active_vehicles),
                "active_vehicles": active_vehicles,
                "newly_flagged_count": len(newly_flagged),
                "newly_flagged": newly_flagged,
            }
        )
    return events


def _extract_rollback_vehicle_masks(rows: List[dict], columns: List[str]) -> Dict[int, np.ndarray]:
    if "rollback_active_vehicles" not in columns:
        return {}

    tracked_ids = set()
    active_lists: List[List[int]] = []
    for row in rows:
        active_ids = _parse_vehicle_id_list(row.get("rollback_active_vehicles", ""))
        newly_flagged = _parse_vehicle_id_list(row.get("rollback_newly_flagged", ""))
        tracked_ids.update(active_ids)
        tracked_ids.update(newly_flagged)
        active_lists.append(active_ids)

    if not tracked_ids:
        return {}

    masks: Dict[int, np.ndarray] = {}
    for vehicle_id in sorted(tracked_ids):
        masks[vehicle_id] = np.array(
            [vehicle_id in active_ids for active_ids in active_lists], dtype=bool
        )
    return masks


def _yolo_usage_mask(rows: List[dict], vid: int) -> np.ndarray:
    """Return boolean mask where YOLO relative measurement was used for global trust."""
    yolo_flag = _col_to_array(rows, f"yolo_rel_meas_used_global_{vid}")
    if not np.any(np.isfinite(yolo_flag)):
        return np.zeros(len(rows), dtype=bool)
    return np.isfinite(yolo_flag) & (yolo_flag >= 0.5)


def _find_relative_uio_log(directory: str, host_id: int) -> str:
    """Return the matching relative UIO log for a host vehicle, if present."""
    if host_id < 0:
        return ""
    candidate_dirs = [
        directory,
        os.path.abspath(os.path.join(directory, "..", "Relative_obs")),
    ]
    matches = []
    for candidate_dir in candidate_dirs:
        pattern = os.path.join(candidate_dir, f"relative_uio_log_V{host_id}*.csv")
        matches.extend(glob.glob(pattern))
    matches = sorted(set(matches), key=os.path.getmtime)
    return matches[-1] if matches else ""

