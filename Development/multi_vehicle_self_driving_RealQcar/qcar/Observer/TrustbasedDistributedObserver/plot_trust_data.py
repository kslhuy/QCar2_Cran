def _load_csv(filepath: str) -> Tuple[List[str], List[Dict[str, str]]]:
    """Return (columns, rows-as-dicts) from a CSV file, filtering corrupt lines."""
    cleaned_lines = []
    with open(filepath, "r", encoding="utf-8", errors="replace") as f:
        for line in f:
            # Remove null bytes which can result from abrupt process termination
            line = line.replace('\x00', '')
            # Skip any lines that are still absurdly long (corrupted)
            if len(line) < 131072:
                cleaned_lines.append(line)
                
    reader = csv.DictReader(cleaned_lines)
    columns = reader.fieldnames or []
    rows = list(reader)
    return columns, rows


def _col_to_array(rows: List[dict], col: str) -> np.ndarray:
    """Convert a column to a float numpy array (NaN for missing/bad)."""
    vals = []
    for row in rows:
        raw = row.get(col, "")
        try:
            vals.append(float(raw))
        except (ValueError, TypeError):
            vals.append(float("nan"))
    return np.array(vals, dtype=float)


def _extract_vehicle_ids(columns: List[str]) -> List[int]:
    ids = set()
    prefixes = {
        "vehicle_present", "trust", "gtrust", "w_neighbor",
        "est_conf", "pred_mode", "est_x", "est_v",
        "v_score", "d_score", "a_score", "h_score",
        "b_score", "q_factor", "local_trust", "global_trust",
        "gamma_host", "gamma_local_peer", "gamma_self",
        "d_host_mean", "d_local_mean", "d_self",
        "mi_dist", "mi_veh_id", "mi_elem_idx", "mi_elem_val",
    }
    for col in columns:
        m = re.search(r"_(\d+)$", col)
        if m and col[: m.start()] in prefixes:
            ids.add(int(m.group(1)))
    return sorted(ids)


def _active_vehicles(rows: List[dict], columns: List[str],
                     vehicle_ids: List[int]) -> List[int]:
    active = []
    for vid in vehicle_ids:
        for prefix in ("vehicle_present", "trust", "gtrust",
                       "w_neighbor", "est_conf", "est_x"):
            col = f"{prefix}_{vid}"
            if col not in columns:
                continue
            arr = _col_to_array(rows, col)
            if prefix == "vehicle_present" and np.nanmax(arr) > 0:
                active.append(vid)
                break
            elif prefix != "vehicle_present" and np.any(np.isfinite(arr)):
                active.append(vid)
                break
    return active


def _plot_series(ax, times, rows, prefix, vids, label_fmt="Vehicle {}",
                 **kwargs):
    """Plot one series per vehicle. Returns count of plotted curves."""
    n = 0
    for vid in vids:
        col = f"{prefix}_{vid}"
        arr = _col_to_array(rows, col)
        if np.any(np.isfinite(arr)):
            ax.plot(times, arr, label=label_fmt.format(vid), **kwargs)
            n += 1
    return n


def _no_data(ax, title: str):
    ax.set_title(title, fontsize=10, fontweight="bold")
    ax.text(0.5, 0.5, "No data", ha="center", va="center",
            transform=ax.transAxes, fontsize=11, color="#888")


def _style(ax, title="", ylabel="", xlabel="", legend=True):
    if title:
        ax.set_title(title, fontsize=10, fontweight="bold")
    if ylabel:
        ax.set_ylabel(ylabel, fontsize=9)
    if xlabel:
        ax.set_xlabel(xlabel, fontsize=9)
    ax.grid(True, linestyle="--", alpha=0.4)
    ax.tick_params(labelsize=8)
    if legend:
        handles, labels = ax.get_legend_handles_labels()
        if handles:
            # Avoid duplicate legend entries for Turn Section if plotted multiple times
            by_label = dict(zip(labels, handles))
            ax.legend(by_label.values(), by_label.keys(), fontsize=7, ncol=max(1, len(by_label) // 2),
                      loc="best", framealpha=0.7)

def _add_turn_sections(ax, times, rows):
    is_turning = _col_to_array(rows, "is_turning")
    if np.any(np.isfinite(is_turning)) and np.any(is_turning > 0):
        import matplotlib.transforms as mtransforms
        trans = mtransforms.blended_transform_factory(ax.transData, ax.transAxes)
        ax.fill_between(times, 0, 1, where=(is_turning >= 1), color='gold', alpha=0.25, transform=trans, label='Turn Section')

