function lim = paddedLimits(ax, fallback)
children = findobj(ax, 'Type', 'line');
y = [];
for i = 1:numel(children)
    y = [y; children(i).YData(:)]; %#ok<AGROW>
end
y = y(isfinite(y));
if isempty(y)
    lim = fallback;
    return;
end
yMin = min(y);
yMax = max(y);
pad = 0.08 * max(1e-6, yMax - yMin);
lim = [min(fallback(1), yMin - pad), max(fallback(2), yMax + pad)];
end

