function summary = buildSummary(cases, focus, attacker, signalSpec)
n = numel(cases);
caseName = strings(n, 1);
file = strings(n, 1);
focusVehicle = repmat(focus, n, 1);
attackerVehicle = repmat(attacker, n, 1);
rollbackEnabled = false(n, 1);
rollbackTriggeredRows = zeros(n, 1);
attackStart_s = nan(n, 1);
attackEnd_s = nan(n, 1);
rollbackEventTimeFromAttack_s = nan(n, 1);
postpredPosErr_m = nan(n, 1);
estPosErr_m = nan(n, 1);
correction_m = nan(n, 1);
correction_percent = nan(n, 1);
postAttackRmse_m = nan(n, 1);
finalAttackRmse_m = nan(n, 1);
finalAttackMax_m = nan(n, 1);
rejectionSignalMean = nan(n, 1);
rejectionSignalMin = nan(n, 1);
rejectionSignalMax = nan(n, 1);

for i = 1:n
    tbl = cases(i).table;
    t = col(tbl, 'time');
    if isfinite(cases(i).attackEnd_s)
        attackMask = t >= cases(i).attackStart_s & t <= cases(i).attackEnd_s;
    else
        attackMask = t >= cases(i).attackStart_s;
    end
    signal = col(tbl, signalSpec.column);

    event = cases(i).event;
    metrics = cases(i).metrics;
    caseName(i) = cases(i).name;
    file(i) = cases(i).relativeFile;
    rollbackEnabled(i) = event.rollback_enabled;
    rollbackTriggeredRows(i) = event.rollback_count;
    attackStart_s(i) = cases(i).attackStart_s;
    attackEnd_s(i) = cases(i).attackEnd_s;
    if event.rollback_triggered
        rollbackEventTimeFromAttack_s(i) = event.time_from_attack_s;
        postpredPosErr_m(i) = event.postpred_pos_err_m;
        estPosErr_m(i) = event.est_pos_err_m;
        correction_m(i) = event.correction_m;
        correction_percent(i) = event.correction_percent;
    else
        correction_m(i) = 0;
        correction_percent(i) = 0;
    end
    postAttackRmse_m(i) = metrics.post_attack_rmse_m;
    finalAttackRmse_m(i) = metrics.est_attack_rmse_m;
    finalAttackMax_m(i) = metrics.est_attack_max_m;
    rejectionSignalMean(i) = finiteMean(signal(attackMask));
    rejectionSignalMin(i) = finiteMin(signal(attackMask));
    rejectionSignalMax(i) = finiteMax(signal(attackMask));
end

rejectionSignal = repmat(string(signalSpec.column), n, 1);
summary = table(caseName, focusVehicle, attackerVehicle, rollbackEnabled, ...
    rollbackTriggeredRows, attackStart_s, attackEnd_s, rollbackEventTimeFromAttack_s, ...
    postpredPosErr_m, estPosErr_m, correction_m, correction_percent, ...
    postAttackRmse_m, finalAttackRmse_m, finalAttackMax_m, ...
    rejectionSignal, rejectionSignalMean, rejectionSignalMin, rejectionSignalMax, file);
end

function printSummary(summary, focus, attacker, signalSpec)
fprintf('\nCompact rollback/anchor summary for target V%d', focus);
if isfinite(attacker)
    fprintf(' under attacker/source V%d', attacker);
end
fprintf('\n');
fprintf('Rejection signal: %s (%s)\n', char(signalSpec.label), char(signalSpec.column));
fprintf('--------------------------------------------------------------------------------\n');
for i = 1:height(summary)
    fprintf('%d) %s\n', i, summary.caseName(i));
    fprintf('   final attack RMSE %.3f m | max %.3f m | rejection mean %.3f\n', ...
        summary.finalAttackRmse_m(i), summary.finalAttackMax_m(i), ...
        summary.rejectionSignalMean(i));
    if isfinite(summary.rollbackEventTimeFromAttack_s(i))
        fprintf('   rollback t-attack %.4f s | post %.3f m -> final %.3f m | corrected %.3f m (%.1f%%)\n', ...
            summary.rollbackEventTimeFromAttack_s(i), summary.postpredPosErr_m(i), ...
            summary.estPosErr_m(i), summary.correction_m(i), summary.correction_percent(i));
    else
        fprintf('   no rollback correction event\n');
    end
end
fprintf('--------------------------------------------------------------------------------\n\n');
end

