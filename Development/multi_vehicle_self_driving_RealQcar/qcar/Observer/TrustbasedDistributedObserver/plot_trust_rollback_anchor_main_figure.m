function markAttackAndRollback(ax, cases, style, showRollback, timeMode)
if isempty(cases)
    return;
end
if timeMode == "absolute"
    attackStart = cases(1).attackStart_s;
    attackEnd = cases(1).attackEnd_s;
else
    attackStart = 0;
    attackEnd = cases(1).attackEnd_s - cases(1).attackStart_s;
end
xline(ax, attackStart, '-', 'Color', style.attackColor, 'LineWidth', 0.9, ...
    'HandleVisibility', 'off');
if isfinite(attackEnd) && attackEnd > attackStart
    xline(ax, attackEnd, '-', 'Color', style.attackColor, 'LineWidth', 0.9, ...
        'HandleVisibility', 'off');
end

if ~showRollback
    return;
end

for i = 1:numel(cases)
    if timeMode == "absolute"
        eventTime = cases(i).event.time_s;
    else
        eventTime = cases(i).event.time_from_attack_s;
    end
    if cases(i).event.rollback_triggered && isfinite(eventTime)
        xline(ax, eventTime, ':', 'Color', style.caseColors(i, :), ...
            'LineWidth', 0.9, 'HandleVisibility', 'off');
    end
end
end

