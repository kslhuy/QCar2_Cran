function files = selectCaseFiles(scriptDir, resultDate, hostId, caseNames)
rootDir = fullfile(scriptDir, 'results');
resultDate = strtrim(string(resultDate));
if strlength(resultDate) == 0
    startDir = rootDir;
else
    startDir = fullfile(rootDir, resultDate);
    if ~isfolder(startDir)
        startDir = rootDir;
    end
end
if ~isfolder(startDir)
    error('Results folder does not exist: %s', rootDir);
end

files = strings(numel(caseNames), 1);
for k = 1:numel(caseNames)
    [selected, selectedPath] = uigetfile( ...
        fullfile(startDir, sprintf('trust_weight_log_V%d*.csv', hostId)), ...
        sprintf('Select CSV for %s', caseNames(k)));
    if isequal(selected, 0)
        error('File selection cancelled.');
    end
    files(k) = erase(string(fullfile(selectedPath, selected)), string(scriptDir) + filesep);
end

fprintf('\nSelected compact figure files:\n');
for k = 1:numel(files)
    fprintf('  %s -> %s\n', caseNames(k), files(k));
end
fprintf('\n');
end

function files = defaultCaseFiles(scriptDir, resultDate)
resultDate = strtrim(string(resultDate));
if strlength(resultDate) == 0
    resultDate = "02-07-26";
end

files = [
    fullfile('results', resultDate, 'case2', 'trust_weight_log_V1_15-32-26_977725.csv')
    fullfile('results', resultDate, 'case2', 'trust_weight_log_V1_15-33-59_274476.csv')
    fullfile('results', resultDate, 'case2', 'trust_weight_log_V1_15-35-25_102224.csv')];

if all(isfile(fullfile(scriptDir, files)))
    return;
end

error(['Default compact-figure files are missing. Pass ''Files'' explicitly ', ...
    'in this order: no rollback, rollback, rollback + anchoring.']);
end

function cases = loadCases(files, caseNames, scriptDir, focus)
cases = repmat(struct(), numel(files), 1);
for i = 1:numel(files)
    filepath = resolveInputFile(files(i), scriptDir);
    tbl = readTrustTable(filepath);
    if ~ismember('time', tbl.Properties.VariableNames)
        error('Missing time column in %s.', filepath);
    end
    if ~ismember(sprintf('est_x_%d', focus), tbl.Properties.VariableNames)
        error('Focus vehicle V%d is not present in %s.', focus, filepath);
    end

    cases(i).name = caseNames(i);
    cases(i).file = string(filepath);
    cases(i).relativeFile = erase(string(filepath), string(scriptDir) + filesep);
    cases(i).table = tbl;
    cases(i).rawTime = col(tbl, 'time');
    [cases(i).attackStart_s, cases(i).attackEnd_s] = attackWindow(tbl, focus);
    cases(i).time = cases(i).rawTime - cases(i).attackStart_s;
    cases(i).event = correctionEvent(tbl, focus, cases(i).attackStart_s);
    cases(i).metrics = attackMetrics(tbl, focus, cases(i).attackStart_s, cases(i).attackEnd_s);
end
end

function filepath = resolveInputFile(fileArg, scriptDir)
filepath = char(fileArg);
if isfile(filepath)
    return;
end

candidate = fullfile(scriptDir, filepath);
if isfile(candidate)
    filepath = candidate;
    return;
end

candidate = fullfile(scriptDir, 'results', filepath);
if isfile(candidate)
    filepath = candidate;
    return;
end

error('File does not exist: %s', filepath);
end

function tbl = readTrustTable(filepath)
opts = detectImportOptions(filepath, 'VariableNamingRule', 'preserve');
try
    opts = setvaropts(opts, opts.VariableNames, 'WhitespaceRule', 'preserve');
catch
end
try
    opts = setvaropts(opts, opts.VariableNames, 'EmptyFieldRule', 'auto');
catch
end
tbl = readtable(filepath, opts);
end

function [attackStart_s, attackEnd_s] = attackWindow(tbl, focus)
startCandidates = [
    firstFinite(col(tbl, 'v2v_attack_start_s'))
    firstFinite(col(tbl, sprintf('inject_attack_start_%d', focus)))];
endCandidates = [
    firstFinite(col(tbl, 'v2v_attack_end_s'))
    firstFinite(col(tbl, sprintf('inject_attack_end_%d', focus)))];

attackStart_s = firstFinite(startCandidates);
attackEnd_s = firstFinite(endCandidates);
if ~isfinite(attackStart_s)
    attackStart_s = 0;
end
if ~isfinite(attackEnd_s) || attackEnd_s <= attackStart_s
    attackEnd_s = NaN;
end
end

function metrics = attackMetrics(tbl, focus, attackStart_s, attackEnd_s)
t = col(tbl, 'time');
post = positionErrorWithReference(tbl, focus, 'postpred');
est = positionErrorWithReference(tbl, focus, 'est');

if isfinite(attackEnd_s)
    mask = t >= attackStart_s & t <= attackEnd_s;
else
    mask = t >= attackStart_s;
end

metrics = struct();
metrics.post_attack_rmse_m = rmse(post(mask));
metrics.est_attack_rmse_m = rmse(est(mask));
metrics.post_attack_max_m = maxOrNan(post(mask));
metrics.est_attack_max_m = maxOrNan(est(mask));
metrics.attack_duration_s = attackEnd_s - attackStart_s;
end

function event = correctionEvent(tbl, focus, attackStart_s)
t = col(tbl, 'time');
post = positionErrorWithReference(tbl, focus, 'postpred');
est = positionErrorWithReference(tbl, focus, 'est');
rb = col(tbl, 'rollback_triggered');
enabled = maxFinite(col(tbl, 'rollback_enabled'));
correction = post - est;

mask = isfinite(t) & isfinite(post) & isfinite(est);
rbMask = mask & isfinite(rb) & rb > 0;
if any(rbMask)
    idxs = find(rbMask);
    [~, relIdx] = max(correction(idxs));
    idx = idxs(relIdx);
elseif any(mask)
    idxs = find(mask);
    [~, relIdx] = max(correction(idxs));
    idx = idxs(relIdx);
else
    idx = NaN;
end

event = struct();
event.index = idx;
event.rollback_enabled = isfinite(enabled) && enabled > 0;
event.rollback_triggered = false;
event.rollback_count = nnz(isfinite(rb) & rb > 0);
event.time_s = NaN;
event.time_from_attack_s = NaN;
event.postpred_pos_err_m = NaN;
event.est_pos_err_m = NaN;
event.correction_m = 0;
event.correction_percent = 0;

if isfinite(idx)
    event.rollback_triggered = isfinite(rb(idx)) && rb(idx) > 0;
    event.time_s = t(idx);
    event.time_from_attack_s = t(idx) - attackStart_s;
    event.postpred_pos_err_m = post(idx);
    event.est_pos_err_m = est(idx);
    event.correction_m = correction(idx);
    if post(idx) > 0
        event.correction_percent = 100 * correction(idx) / post(idx);
    end
end
end

function attacker = inferAttacker(cases, focus)
attacker = NaN;
for i = 1:numel(cases)
    attacker = firstFinite(col(cases(i).table, sprintf('inject_attack_attacker_%d', focus)));
    if isfinite(attacker)
        attacker = round(attacker);
        return;
    end
end

for i = 1:numel(cases)
    names = string(cases(i).table.Properties.VariableNames);
    mask = startsWith(names, "inject_attack_attacker_");
    attackCols = names(mask);
    for k = 1:numel(attackCols)
        attacker = firstFinite(col(cases(i).table, attackCols(k)));
        if isfinite(attacker)
            attacker = round(attacker);
            return;
        end
    end
end
end

function spec = chooseRejectionSignal(cases, focus, attacker)
spec = struct();
spec.column = "";
spec.label = "unavailable";
spec.ylabel = "signal [-]";
spec.isTrust = false;

if isfinite(attacker)
    attacker = round(attacker);
    if attacker == focus
        candidate = sprintf('w0_final_%d', focus);
        if hasColumnAny(cases, candidate)
            spec.column = candidate;
            spec.label = "direct attacked-source weight";
            spec.ylabel = "weight [-]";
            return;
        end
    end

    candidate = sprintf('w_neighbor_from_v%d_to_%d', attacker, focus);
    if hasColumnAny(cases, candidate)
        spec.column = candidate;
        spec.label = "attacker source weight";
        spec.ylabel = "weight [-]";
        return;
    end

    candidate = sprintf('trust_%d', attacker);
    if hasColumnAny(cases, candidate)
        spec.column = candidate;
        spec.label = "attacker trust";
        spec.ylabel = "trust [-]";
        spec.isTrust = true;
        return;
    end
end

candidate = sprintf('w0_final_%d', focus);
if hasColumnAny(cases, candidate)
    spec.column = candidate;
    spec.label = "target direct weight";
    spec.ylabel = "weight [-]";
    return;
end

candidate = sprintf('w_neighbor_sum_final_%d', focus);
if hasColumnAny(cases, candidate)
    spec.column = candidate;
    spec.label = "target neighbor total weight";
    spec.ylabel = "weight [-]";
    return;
end

candidate = sprintf('trust_%d', focus);
if hasColumnAny(cases, candidate)
    spec.column = candidate;
    spec.label = "target trust";
    spec.ylabel = "trust [-]";
    spec.isTrust = true;
    return;
end

error('Could not find a rejection signal column for target V%d.', focus);
end

function spec = chooseTrustDropSignal(cases, focus, attacker)
spec = struct();
spec.column = "";
spec.label = "unavailable";

if isfinite(attacker)
    vehicle = round(attacker);
else
    vehicle = focus;
end

candidatePairs = {
    sprintf('gtrust_%d', vehicle), 'generalized trust'
    sprintf('trust_%d', vehicle), 'final trust'
    sprintf('local_trust_%d', vehicle), 'local trust'
    sprintf('global_trust_%d', vehicle), 'global trust'};

for i = 1:size(candidatePairs, 1)
    candidate = candidatePairs{i, 1};
    if hasColumnAny(cases, candidate)
        spec.column = candidate;
        spec.label = candidatePairs{i, 2};
        return;
    end
end

error('Could not find a trust-drop signal column for V%d.', vehicle);
end

