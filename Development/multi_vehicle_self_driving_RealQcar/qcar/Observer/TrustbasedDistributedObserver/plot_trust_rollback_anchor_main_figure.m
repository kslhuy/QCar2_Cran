function summary = plot_trust_rollback_anchor_main_figure(varargin)
%PLOT_TRUST_ROLLBACK_ANCHOR_MAIN_FIGURE Compact proof-of-concept figure.
%
% The expected file order is:
%   1. no rollback
%   2. rollback
%   3. rollback + anchoring
%
% Common usage:
%   plot_trust_rollback_anchor_main_figure
%   plot_trust_rollback_anchor_main_figure('Focus', 2)
%   plot_trust_rollback_anchor_main_figure('Files', files, 'Focus', 2)
%   plot_trust_rollback_anchor_main_figure('Files', files, 'Focus', 2, 'Attacker', 1)
%   plot_trust_rollback_anchor_main_figure('Save', true, 'OutputDir', 'paper_figures')
%   plot_trust_rollback_anchor_main_figure('TimeMode', 'relative', 'TimeWindow', [-2 10])
%   plot_trust_rollback_anchor_main_figure('PlotTrajectory', true)
%
% The figure contains:
%   (a) final position-estimation error for the three cases
%   (b) attacker/source rejection signal, preferably source weight
%   (c) generalized/final trust drop for the attacked source
%   (d) rollback correction: before/after rollback curves
%
% A second XY trajectory figure is also generated by default. It compares
% the reference and final estimated trajectory for the three cases.

parser = inputParser;
addParameter(parser, 'Files', strings(0, 1), @(x) isstring(x) || iscell(x) || ischar(x));
addParameter(parser, 'CaseNames', strings(0, 1), @(x) isstring(x) || iscell(x) || ischar(x));
addParameter(parser, 'Focus', 0, @(x) isscalar(x) && isnumeric(x));
addParameter(parser, 'Attacker', NaN, @(x) isscalar(x) && isnumeric(x));
addParameter(parser, 'Host', 1, @(x) isscalar(x) && isnumeric(x));
addParameter(parser, 'ResultDate', '', @(x) ischar(x) || isstring(x));
addParameter(parser, 'SelectFiles', true, @(x) islogical(x) || isnumeric(x));
addParameter(parser, 'Save', true, @(x) islogical(x) || isnumeric(x));
addParameter(parser, 'OutputDir', 'paper_figures', @(x) ischar(x) || isstring(x));
addParameter(parser, 'Formats', ["png", "pdf"], @(x) isstring(x) || iscell(x) || ischar(x));
addParameter(parser, 'TimeMode', 'absolute', @(x) ischar(x) || isstring(x));
addParameter(parser, 'TimeWindow', [5 20], @(x) isempty(x) || (isnumeric(x) && numel(x) == 2));
addParameter(parser, 'RollbackZoom', [], @(x) isempty(x) || (isnumeric(x) && numel(x) == 2));
addParameter(parser, 'PlotTrajectory', true, @(x) islogical(x) || isnumeric(x));
addParameter(parser, 'TrajectoryTimeWindow', [], @(x) isempty(x) || (isnumeric(x) && numel(x) == 2));
addParameter(parser, 'TrajectoryShowPostpred', true, @(x) islogical(x) || isnumeric(x));
addParameter(parser, 'Dpi', 600, @(x) isscalar(x) && isnumeric(x));
parse(parser, varargin{:});
args = parser.Results;

scriptDir = fileparts(mfilename('fullpath'));
focus = double(args.Focus);
attacker = double(args.Attacker);

caseNames = normalizeStringArray(args.CaseNames);
if isempty(caseNames)
    caseNames = [
        "No rollback"
        "Rollback"
        "Rollback + anchoring"];
end

files = normalizeStringArray(args.Files);
if isempty(files) && logical(args.SelectFiles)
    files = selectCaseFiles(scriptDir, string(args.ResultDate), double(args.Host), caseNames);
elseif isempty(files)
    files = defaultCaseFiles(scriptDir, string(args.ResultDate));
end
if numel(files) ~= numel(caseNames)
    error('Number of files (%d) must match number of case names (%d).', numel(files), numel(caseNames));
end

cases = loadCases(files, caseNames, scriptDir, focus);
if ~isfinite(attacker)
    attacker = inferAttacker(cases, focus);
end
signalSpec = chooseRejectionSignal(cases, focus, attacker);
trustSpec = chooseTrustDropSignal(cases, focus, attacker);

style = paperStyle();
set(groot, 'defaultAxesFontName', style.fontName);
set(groot, 'defaultTextFontName', style.fontName);

timeWindow = double(args.TimeWindow);
rollbackZoom = double(args.RollbackZoom);
timeMode = normalizeTimeMode(args.TimeMode);
summary = buildSummary(cases, focus, attacker, signalSpec);
printSummary(summary, focus, attacker, signalSpec);

fig = makeMainFigure(cases, focus, attacker, signalSpec, trustSpec, style, timeWindow, rollbackZoom, timeMode);
if logical(args.PlotTrajectory)
    trajectoryFig = makeTrajectoryFigure(cases, focus, style, ...
        double(args.TrajectoryTimeWindow), timeMode, logical(args.TrajectoryShowPostpred));
else
    trajectoryFig = [];
end

outputDir = resolveOutputDir(args.OutputDir, scriptDir);
formats = normalizeStringArray(args.Formats);
if logical(args.Save)
    ensureFolder(outputDir);
    writetable(summary, fullfile(outputDir, sprintf('rollback_anchor_main_summary_V%d.csv', focus)));
end
finishFigure(fig, sprintf('rollback_anchor_main_V%d', focus), outputDir, formats, logical(args.Save), args.Dpi);
if ~isempty(trajectoryFig)
    finishFigure(trajectoryFig, sprintf('rollback_anchor_xy_trajectories_V%d', focus), ...
        outputDir, formats, logical(args.Save), args.Dpi);
end
if logical(args.Save)
    fprintf('Saved compact rollback/anchor figures to: %s\n', outputDir);
end
end

function fig = makeMainFigure(cases, focus, attacker, signalSpec, trustSpec, style, timeWindow, rollbackZoom, timeMode)
fig = figure('Name', 'Rollback and Anchoring Main Figure', 'Color', 'w', ...
    'Units', 'centimeters', 'Position', [2 2 18 20]);
layout = tiledlayout(fig, 4, 1, 'TileSpacing', 'compact', 'Padding', 'compact');

ax1 = nexttile(layout);
plotPositionErrorPanel(ax1, cases, focus, style, timeWindow, timeMode);

ax2 = nexttile(layout);
plotRejectionPanel(ax2, cases, attacker, signalSpec, style, timeWindow, timeMode);

ax3 = nexttile(layout);
plotTrustDropPanel(ax3, cases, attacker, trustSpec, style, timeWindow, timeMode);

ax4 = nexttile(layout);
plotRollbackCorrectionPanel(ax4, cases, focus, style, timeWindow, rollbackZoom, timeMode);

title(layout, sprintf('Rollback and anchoring effect for target V%d', focus), ...
    'FontName', style.fontName, 'FontSize', style.titleSize + 1, 'FontWeight', 'bold');
end

function fig = makeTrajectoryFigure(cases, focus, style, timeWindow, timeMode, showPostpred)
n = numel(cases);
figWidth = max(18, 6.2 * n);
fig = figure('Name', 'Rollback and Anchoring XY Trajectories', 'Color', 'w', ...
    'Units', 'centimeters', 'Position', [2 2 figWidth 7.8]);
layout = tiledlayout(fig, 1, n, 'TileSpacing', 'compact', 'Padding', 'compact');
xyLimits = trajectoryLimits(cases, focus, timeWindow, timeMode, showPostpred);

for i = 1:n
    ax = nexttile(layout);
    plotTrajectoryCasePanel(ax, cases(i), focus, style, xyLimits, timeWindow, ...
        timeMode, showPostpred, i);
end

title(layout, sprintf('XY trajectory comparison for target V%d', focus), ...
    'FontName', style.fontName, 'FontSize', style.titleSize + 1, ...
    'FontWeight', 'bold');
end

function plotTrajectoryCasePanel(ax, caseData, focus, style, xyLimits, timeWindow, timeMode, showPostpred, caseIndex)
hold(ax, 'on');
tbl = caseData.table;
t = caseTime(caseData, timeMode);
mask = trajectoryTimeMask(t, timeWindow);
colorIndex = mod(caseIndex - 1, size(style.caseColors, 1)) + 1;
caseColor = style.caseColors(colorIndex, :);

refX = col(tbl, sprintf('ref_x_%d', focus));
refY = col(tbl, sprintf('ref_y_%d', focus));
postX = col(tbl, sprintf('postpred_x_%d', focus));
postY = col(tbl, sprintf('postpred_y_%d', focus));
estX = col(tbl, sprintf('est_x_%d', focus));
estY = col(tbl, sprintf('est_y_%d', focus));

plotXYFinite(ax, refX(mask), refY(mask), '--', style.referenceColor, ...
    style.lineWidth, 'reference');
if showPostpred
    postColor = lightenColor(caseColor, 0.55);
    plotXYFinite(ax, postX(mask), postY(mask), ':', postColor, ...
        style.lineWidth, 'before rollback');
end
plotXYFinite(ax, estX(mask), estY(mask), '-', caseColor, ...
    style.lineWidth + 0.25, 'final estimate');

attackStart = eventTimeForMode(caseData.attackStart_s, caseData, timeMode);
attackEnd = eventTimeForMode(caseData.attackEnd_s, caseData, timeMode);
eventTime = eventTimeForMode(caseData.event.time_s, caseData, timeMode);
markXYEvent(ax, t, estX, estY, attackStart, 'o', style.attackColor, 'attack start');
markXYEvent(ax, t, estX, estY, attackEnd, 's', style.attackColor, 'attack end');
if caseData.event.rollback_triggered
    markXYEvent(ax, t, estX, estY, eventTime, '^', caseColor, 'rollback event');
end

if all(isfinite(xyLimits))
    xlim(ax, xyLimits(1:2));
    ylim(ax, xyLimits(3:4));
end
axis(ax, 'equal');
grid(ax, 'on');
ax.GridAlpha = style.gridAlpha;
ax.FontName = style.fontName;
ax.FontSize = style.fontSize;
ax.LineWidth = 0.8;
box(ax, 'on');
xlabel(ax, 'x [m]', 'FontSize', style.fontSize);
ylabel(ax, 'y [m]', 'FontSize', style.fontSize);

titleText = sprintf('(%c) %s', char('a' + caseIndex - 1), caseData.name);
if isfield(caseData, 'metrics') && isfinite(caseData.metrics.est_attack_rmse_m)
    titleText = sprintf('%s | RMSE %.3f m', titleText, caseData.metrics.est_attack_rmse_m);
end
title(ax, titleText, 'FontSize', style.titleSize, 'FontWeight', 'bold', ...
    'Interpreter', 'none');
legend(ax, 'Location', 'best', 'FontSize', style.fontSize - 1, ...
    'Interpreter', 'none');
end

function xyLimits = trajectoryLimits(cases, focus, timeWindow, timeMode, showPostpred)
allX = [];
allY = [];
for i = 1:numel(cases)
    tbl = cases(i).table;
    t = caseTime(cases(i), timeMode);
    mask = trajectoryTimeMask(t, timeWindow);
    if showPostpred
        prefixes = ["ref", "est", "postpred"];
    else
        prefixes = ["ref", "est"];
    end
    for k = 1:numel(prefixes)
        prefix = char(prefixes(k));
        x = col(tbl, sprintf('%s_x_%d', prefix, focus));
        y = col(tbl, sprintf('%s_y_%d', prefix, focus));
        valid = mask & isfinite(x) & isfinite(y);
        allX = [allX; x(valid)]; %#ok<AGROW>
        allY = [allY; y(valid)]; %#ok<AGROW>
    end
end

if isempty(allX) || isempty(allY)
    xyLimits = [0 1 0 1];
    return;
end

xMin = min(allX);
xMax = max(allX);
yMin = min(allY);
yMax = max(allY);
xPad = 0.08 * max(1e-6, xMax - xMin);
yPad = 0.08 * max(1e-6, yMax - yMin);
xyLimits = [xMin - xPad, xMax + xPad, yMin - yPad, yMax + yPad];
end

function mask = trajectoryTimeMask(t, timeWindow)
mask = isfinite(t);
if isempty(timeWindow)
    return;
end
if numel(timeWindow) == 2 && all(isfinite(timeWindow)) && timeWindow(2) > timeWindow(1)
    mask = mask & t >= timeWindow(1) & t <= timeWindow(2);
end
end

function eventTime = eventTimeForMode(rawEventTime, caseData, timeMode)
if ~isfinite(rawEventTime)
    eventTime = NaN;
elseif timeMode == "absolute"
    eventTime = rawEventTime;
else
    eventTime = rawEventTime - caseData.attackStart_s;
end
end

function plotXYFinite(ax, x, y, lineStyle, color, lineWidth, displayName)
mask = isfinite(x) & isfinite(y);
if any(mask)
    plot(ax, x(mask), y(mask), 'LineStyle', lineStyle, 'Color', color, ...
        'LineWidth', lineWidth, 'DisplayName', displayName);
end
end

function markXYEvent(ax, t, x, y, eventTime, marker, color, displayName)
[xEvent, yEvent] = nearestFinitePoint(t, x, y, eventTime);
if ~isfinite(xEvent) || ~isfinite(yEvent)
    return;
end
plot(ax, xEvent, yEvent, marker, 'Color', color, ...
    'MarkerFaceColor', 'w', 'MarkerSize', 5.5, 'LineWidth', 1.0, ...
    'DisplayName', displayName);
end

function [xEvent, yEvent] = nearestFinitePoint(t, x, y, eventTime)
xEvent = NaN;
yEvent = NaN;
if ~isfinite(eventTime)
    return;
end
mask = isfinite(t) & isfinite(x) & isfinite(y);
if ~any(mask)
    return;
end
idxs = find(mask);
[~, relIdx] = min(abs(t(idxs) - eventTime));
idx = idxs(relIdx);
xEvent = x(idx);
yEvent = y(idx);
end

function color = lightenColor(color, amount)
amount = min(max(amount, 0.0), 1.0);
color = color + amount * (1.0 - color);
color = min(max(color, 0.0), 1.0);
end

